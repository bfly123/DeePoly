import torch
import torch.nn as nn
import numpy as np
from typing import Dict, Tuple, Optional
import torch.optim as optim

class BaseNet(nn.Module):
    """Base neural network class"""

    def __init__(
        self, config, use_periodic: bool = False
    ):
        super().__init__()
        self.config = config
        self.use_periodic = use_periodic
        self.in_dim = config.n_dim
        self.hidden_dims = config.hidden_dims
        self.out_dim = config.n_eqs

        # Calculate input dimension - unified approach
        periodic_multiplier = 3 if use_periodic else 1
        actual_in = self.in_dim * periodic_multiplier

        # Build network layers
        layers = []
        dims = [actual_in] + list(self.hidden_dims)
        for i in range(len(dims) - 1):
            layers.extend(
                [nn.Linear(dims[i], dims[i + 1], dtype=torch.float64), nn.Tanh()]
            )

        self.net = nn.Sequential(*layers)
        self.out = nn.Linear(self.hidden_dims[-1], self.out_dim, bias=False, dtype=torch.float64)


    def forward(self, x: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        """Forward propagation with unified periodic handling

        Args:
            x: Input tensor

        Returns:
            Tuple[torch.Tensor, torch.Tensor]: (Hidden layer output, Final output)
        """
        # Apply periodic features if enabled - no branching in computation
        features = [x]
        if self.use_periodic:
            features.extend([
                torch.sin(2 * np.pi * x),
                torch.cos(2 * np.pi * x)
            ])

        x_processed = torch.cat(features, dim=-1) if len(features) > 1 else x
        h = self.net(x_processed)
        return h, self.out(h)

    def derivative_h(self, x: torch.Tensor) -> torch.Tensor:
        """Calculate derivative of hidden layer output with respect to input

        Args:
            x: Input tensor

        Returns:
            torch.Tensor: Derivative
        """
        h, _ = self.forward(x)
        h_x = torch.autograd.grad(
            h, x, grad_outputs=torch.ones_like(h), create_graph=True
        )[0]
        return h_x

    @staticmethod
    def gradients(outputs: torch.Tensor, inputs: torch.Tensor) -> Tuple[torch.Tensor]:
        """Calculate gradients

        Args:
            outputs: Output tensor
            inputs: Input tensor

        Returns:
            Tuple[torch.Tensor]: Gradients
        """
        return torch.autograd.grad(
            outputs, inputs, grad_outputs=torch.ones_like(outputs), create_graph=True
        )

    def compute_pde_operators(
        self,
        U: torch.Tensor,
        x_train: torch.Tensor
    ) -> Dict[str, list]:
        """Compute PDE operators - unified auto code generation area

        This method is automatically generated by auto_spotter based on config.json.
        All problem types share the same operator computation code.

        Args:
            U: Model output, shape [N, n_eqs]
            x_train: Training coordinates, shape [N, n_dim]

        Returns:
            Dict containing all operators:
                {
                    "L1": [tensor1, tensor2, ...],
                    "L2": [tensor1, tensor2, ...],
                    "F": [tensor1, tensor2, ...],
                    "N": [tensor1, tensor2, ...],
                    "S": [tensor1, tensor2, ...]
                }

        Example:
            >>> ops = self.compute_pde_operators(U, x_train)
            >>> L1, L2, F, N = ops['L1'], ops['L2'], ops['F'], ops['N']
        """

# auto code begin
# Config signature: {"F": ["0"], "L1": ["-0.0001*diff(u,x,2)+diff(u,y)"], "L2": ["0"], "N": ["-5*u+5*u**3"]}
        # Extract physical quantities from output
        u = U[..., 0]

        # Calculate derivatives in each direction
        du_x = self.gradients(u, x_train)[0][..., 0]
        du_y = self.gradients(u, x_train)[0][..., 1]

        # Calculate 2nd-order derivatives
        du_xx = self.gradients(du_x, x_train)[0][..., 0]

        # L1 operators
        L1 = [-0.0001*du_xx+du_y]

        # L2 operators
        L2 = [0]

        # F operators
        F = [0]

        # N operators
        N = [-5*u+5*u**3]


        # S operators (default)
        S = [0]

# auto code end

        return {
            "L1": L1,
            "L2": L2,
            "F": F,
            "N": N,
            "S": S
        }

    def _prepare_physics_loss_data(self, data_GPU: Dict, **kwargs) -> Dict:
        """Unified data extraction for physics_loss

        This method extracts all commonly used data from data_GPU and kwargs,
        eliminating repetitive extraction code in each net.py.

        Args:
            data_GPU: GPU data dictionary
            **kwargs: Additional parameters (e.g., dt, step)

        Returns:
            Dict containing extracted data:
                - x_train: Training coordinates (torch.Tensor)
                - U: Model prediction output (torch.Tensor)
                - dt: Time step size (float)
                - step: Training step type (str)
                - U_current: Current solution (torch.Tensor or None)
                - param: Physical parameters dict
                - Re: Reynolds number (float)
                - nu: Viscosity (float)
                - x_bd: Boundary coordinates (torch.Tensor or None)
                - u_bd: Boundary values (torch.Tensor or None)
                - source: Source term (torch.Tensor or None, for LinearPDE)
                - u_train: Training data (torch.Tensor or None, for FuncFitting)
        """
        extracted = {}

        # 1. Extract kwargs parameters
        extracted['dt'] = kwargs.get('dt', 0)
        extracted['step'] = kwargs.get('step', 'pre')

        # 2. Extract coordinates (handle both "x" and "x_train" naming)
        extracted['x_train'] = data_GPU.get("x_train", data_GPU.get("x", None))

        # 3. Execute model forward propagation
        if extracted['x_train'] is not None:
            _, extracted['U'] = self(extracted['x_train'])
        else:
            extracted['U'] = None

        # 4. Extract physical parameters
        extracted['param'] = data_GPU.get("param", [{"Re": 1.0, "nu": 1.0}])
        if extracted['param'] and len(extracted['param']) > 0:
            extracted['Re'] = extracted['param'][0].get("Re", 1.0)
            extracted['nu'] = extracted['param'][0].get("nu", 1.0)
        else:
            extracted['Re'] = 1.0
            extracted['nu'] = 1.0

        # 5. Extract time/pseudo-time related data
        extracted['U_current'] = data_GPU.get("U_current", None)

        # 6. Extract boundary data (for quick access in physics_loss)
        extracted['x_bd'] = data_GPU.get("x_bd", None)
        extracted['u_bd'] = data_GPU.get("u_bd", None)
        extracted['global_boundary_dict'] = data_GPU.get("global_boundary_dict", None)

        # 7. Extract solver-specific data
        extracted['source'] = data_GPU.get("source", None)  # LinearPDE
        extracted['u_train'] = data_GPU.get("u_train", None)  # FuncFitting

        return extracted

    def compute_total_loss(
        self,
        pde_loss: torch.Tensor,
        data_GPU: Dict,
        boundary_weight: float = 10.0
    ) -> torch.Tensor:
        """Unified total loss computation

        Args:
            pde_loss: PDE residual loss
            data_GPU: GPU data dictionary
            boundary_weight: Weight for boundary condition loss

        Returns:
            torch.Tensor: Total loss (pde_loss + boundary_weight * boundary_loss)
        """
        boundary_loss = self._compute_boundary_loss(data_GPU)
        return pde_loss + boundary_weight * boundary_loss

    def physics_loss(self, data_GPU: Dict, **kwargs) -> torch.Tensor:
        """Calculate physics loss

        Args:
            data_GPU: GPU data dictionary containing GPU data required for training
            data_train: Training data dictionary containing CPU data required for training
            **kwargs: Additional parameters, specific implementations can add as needed

        Returns:
            torch.Tensor: Loss value
        """
        raise NotImplementedError("Subclasses must implement physics_loss method")

    def prepare_gpu_data(self, data: Dict, U_current: np.ndarray = None) -> Dict:
        """Unified GPU data preparation for all problem types

        This method eliminates 210 lines of duplicated code across 4 net.py files.

        Args:
            data: Input data dictionary
            U_current: Current solution (optional, for time-stepping problems)

        Returns:
            gpu_data: Dictionary containing GPU tensors
        """
        gpu_data = {}

        # 1. Transfer coordinates to GPU (unified key name: x_train)
        gpu_data["x_train"] = torch.tensor(
            data["x"], dtype=torch.float64,
            device=self.config.device, requires_grad=True
        )

        # 2. Handle U_current for time-stepping problems
        if U_current is not None:
            gpu_data["U_current"] = torch.tensor(
                U_current, dtype=torch.float64, device=self.config.device
            )

        # 3. Handle source term for linear PDEs
        if "source" in data:
            gpu_data["source"] = torch.tensor(
                data["source"], dtype=torch.float64, device=self.config.device
            )

        # 4. Unified boundary condition processing
        boundary_gpu_data = self.prepare_boundary_gpu_data(data)
        gpu_data.update(boundary_gpu_data)

        # 5. Extract x_bd/u_bd arrays (eliminates 87 lines of duplicated code)
        self._extract_boundary_arrays(data, gpu_data)

        # 6. Add parameter data
        gpu_data["param"] = [{"Re": 1.0, "nu": 1.0}]

        return gpu_data

    def _extract_boundary_arrays(self, data: Dict, gpu_data: Dict) -> None:
        """Extract boundary coordinate and value arrays

        This method eliminates 87 lines of duplicated code across 3 net.py files
        (FixIteration, PseudoTime, TimePDE).

        Args:
            data: Input data dictionary
            gpu_data: GPU data dictionary to update
        """
        if "global_boundary_dict" not in data or not data["global_boundary_dict"]:
            gpu_data["x_bd"] = torch.zeros(
                (0, self.config.n_dim), dtype=torch.float64, device=self.config.device
            )
            gpu_data["u_bd"] = torch.zeros(
                (0, self.config.n_eqs), dtype=torch.float64, device=self.config.device
            )
            return

        x_bd_list = []
        u_bd_list = []

        for var_idx in data["global_boundary_dict"]:
            for bc_type in data["global_boundary_dict"][var_idx]:
                if "x" in data["global_boundary_dict"][var_idx][bc_type]:
                    x_bd = data["global_boundary_dict"][var_idx][bc_type]["x"]
                    u_bd = data["global_boundary_dict"][var_idx][bc_type]["values"]
                    if isinstance(x_bd, np.ndarray) and x_bd.size > 0:
                        x_bd_list.append(x_bd)
                        u_bd_list.append(u_bd)

        if x_bd_list:
            gpu_data["x_bd"] = torch.tensor(
                np.vstack(x_bd_list), dtype=torch.float64,
                device=self.config.device, requires_grad=True
            )
            gpu_data["u_bd"] = torch.tensor(
                np.vstack(u_bd_list), dtype=torch.float64, device=self.config.device
            )
        else:
            gpu_data["x_bd"] = torch.zeros(
                (0, self.config.n_dim), dtype=torch.float64, device=self.config.device
            )
            gpu_data["u_bd"] = torch.zeros(
                (0, self.config.n_eqs), dtype=torch.float64, device=self.config.device
            )

    def prepare_train_data(self, data: Dict) -> Dict:
        """Convert data to tensors with unified processing - eliminate None checking branches

        Args:
            data: Raw data dictionary

        Returns:
            Dict: Data dictionary with converted tensors
        """
        return {
            key: torch.tensor(value, dtype=torch.float64, device=self.config.device)
            for key, value in data.items()
            if value is not None
        }

    @staticmethod
    def model_init():
        """Initialize model

        Args:
            config: Configuration object

        Returns:
            BaseNet: Initialized model
        """
        raise NotImplementedError("Subclasses must implement model_init method")


    def train_net(self,data, model, data_GPU, **kwargs):
      # max_retries: default=1, allow 0 for no retries (single attempt)
      max_retries = getattr(self.config, 'max_retries', 1)
      retry_count = 0
      best_loss = float("inf")
      best_model = None

      # Get time step for tolerance calculation (dt for time_pde, dτ for general_pde)
      dt = kwargs.get('dt', 1.0)

      # Training loop: retry_count <= max_retries gives (max_retries+1) total attempts
      # max_retries=0 → 1 attempt, max_retries=1 → 2 attempts
      while retry_count <= max_retries:
          if retry_count > 0:
              print(
                  f"Retry {retry_count}/{max_retries}, changing random seed to {self.config.seed + retry_count}"
              )
              torch.manual_seed(self.config.seed + retry_count)
              np.random.seed(self.config.seed + retry_count)
              #model = BaseNet.model_init(config).to(config.device)

          lr_adam = self.config.learning_rate
          # Use PINN-style Adam parameters for better convergence on nonlinear PDEs
          optimizer_adam = optim.Adam(model.parameters(), lr=lr_adam, betas=(0.999, 0.999))
          optimizer_lbfgs = optim.LBFGS(model.parameters(), lr=0.1)

          # Adaptive learning rate adjustment (improved strategy from PINN)
          # More aggressive decay thresholds to match PINN performance
          lr_thresholds = [1.0, 0.5, 1e-2, 1e-3, 1e-4]
          lr_values = [self.config.learning_rate, 0.005, 0.003, 0.001, 0.0005, 0.0001]
          lr_history = []

          def adjust_learning_rate(optimizer, current_loss, epoch):
              lr_history.append(current_loss)
              current_lr = optimizer.param_groups[0]['lr']

              # Select learning rate based on loss thresholds (only decrease, no increase)
              target_lr = lr_values[0]  # Start with max lr
              for i, threshold in enumerate(lr_thresholds):
                  if current_loss < threshold:
                      target_lr = lr_values[i + 1]

              # Only allow lr to decrease (prevent oscillation)
              target_lr = min(target_lr, current_lr)

              # Apply change if significant difference
              if abs(current_lr - target_lr) > 1e-8:
                  for param_group in optimizer.param_groups:
                      param_group['lr'] = target_lr
                  return True, target_lr
              return False, current_lr

          #data_train = BaseNet.prepare_train_data(data)
          model = model.to(self.config.device)

          def closure():
              optimizer_adam.zero_grad()
              loss = model.physics_loss(data_GPU, **kwargs)
              loss.backward()
              return loss

          # Adam optimization
          final_loss = None
          # Tolerance scales with time step: smaller dt allows larger relative error
          tolerance = self.config.DNNtol * dt

          for epoch in range(self.config.epochs_adam):
              optimizer_adam.zero_grad()
              loss = model.physics_loss(data_GPU, **kwargs)
              loss.backward()
              optimizer_adam.step()
              final_loss = loss.item()

              # Adjust learning rate based on loss
              lr_changed, current_lr = adjust_learning_rate(optimizer_adam, final_loss, epoch)

              if final_loss < tolerance:
                  break
              if epoch % 1000 == 0:
                  print(f" Adam Epoch {epoch}, Loss: {final_loss:.6e}, LR: {current_lr:.6e}")
              if lr_changed:
                  print(f"   Learning rate adjusted to {current_lr:.6e} at epoch {epoch}, loss {final_loss:.6e}")

          print(f"Final Adam Loss: {final_loss}")
  #
          # LBFGS optimization
          if self.config.epochs_lbfgs > 0:
              for epoch in range(self.config.epochs_lbfgs):
                  optimizer_lbfgs.zero_grad()
                  loss = model.physics_loss(data_GPU, **kwargs)
                  loss.backward()
                  optimizer_lbfgs.step(closure)
                  final_loss = loss.item()

                  if final_loss < tolerance:
                      break
                  if epoch % 100 == 0:
                      print(f"LBFGS Epoch {epoch}, Loss: {final_loss}")

          # Save best model
          if final_loss < best_loss:
              best_loss = final_loss
              best_model = model.state_dict().copy()

          if final_loss < tolerance:
              print(f"Target accuracy {tolerance:.2e} (DNNtol={self.config.DNNtol:.2e} * dt={dt:.2e}) achieved, stopping retries")
              break

          retry_count += 1

      if best_model is not None:
          current_model_id = id(model.state_dict())
          best_model_id = id(best_model)
          if current_model_id != best_model_id:
              model.load_state_dict(best_model)
              print(f"Using best model, loss value: {best_loss}")

      return model
